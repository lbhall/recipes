class RecipeCreateViewTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.user = make_user()
        cls.category = Category.objects.create(name='Dinner')

    def test_anonymous_redirected_to_login(self):
        resp = self.client.get(reverse('cookbook:recipe_create'))
        self.assertEqual(resp.status_code, 302)
        self.assertIn(reverse('login'), resp.url)

    def test_authenticated_get_renders_blank_form(self):
        self.client.force_login(self.user)
        resp = self.client.get(reverse('cookbook:recipe_create'))
        self.assertEqual(resp.status_code, 200)
        self.assertIn('ingredient_formset', resp.context)

    def test_create_saves_recipe_author_and_children(self):
        self.client.force_login(self.user)
        resp = self.client.post(
            reverse('cookbook:recipe_create'),
            recipe_post_data(categories=[self.category.pk]),
        )
        self.assertEqual(resp.status_code, 302)
        recipe = Recipe.objects.get(name='Test Soup')
        self.assertEqual(recipe.author, self.user)
        self.assertEqual(recipe.ingredients.count(), 1)
        self.assertEqual(recipe.ingredients.first().display, '2 cups flour')
        self.assertEqual(recipe.steps.count(), 1)
        self.assertIn(self.category, recipe.categories.all())

    def test_invalid_child_formset_rerenders_without_saving(self):
        self.client.force_login(self.user)
        # order is a required PositiveIntegerField on the ingredient row.
        resp = self.client.post(
            reverse('cookbook:recipe_create'),
            recipe_post_data(**{'ingredients-0-order': 'not-a-number'}),
        )
        self.assertEqual(resp.status_code, 200)
        self.assertFalse(Recipe.objects.filter(name='Test Soup').exists())


class RecipeUpdateDeleteViewTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.owner = make_user('owner')
        cls.other = make_user('intruder')

    def setUp(self):
        self.recipe = make_recipe(self.owner, name='My Recipe')

    def test_owner_can_update(self):
        self.client.force_login(self.owner)
        resp = self.client.post(
            reverse('cookbook:recipe_update', kwargs={'pk': self.recipe.pk}),
            recipe_post_data(name='Renamed'),
        )
        self.assertEqual(resp.status_code, 302)
        self.recipe.refresh_from_db()
        self.assertEqual(self.recipe.name, 'Renamed')

    def test_non_owner_cannot_update(self):
        self.client.force_login(self.other)
        resp = self.client.get(
            reverse('cookbook:recipe_update', kwargs={'pk': self.recipe.pk})
        )
        self.assertEqual(resp.status_code, 403)

    def test_owner_can_delete(self):
        self.client.force_login(self.owner)
        resp = self.client.post(
            reverse('cookbook:recipe_delete', kwargs={'pk': self.recipe.pk})
        )
        self.assertRedirects(resp, reverse('cookbook:recipe_list'))
        self.assertFalse(Recipe.objects.filter(pk=self.recipe.pk).exists())

    def test_non_owner_cannot_delete(self):
        self.client.force_login(self.other)
        resp = self.client.post(
            reverse('cookbook:recipe_delete', kwargs={'pk': self.recipe.pk})
        )
        self.assertEqual(resp.status_code, 403)
        self.assertTrue(Recipe.objects.filter(pk=self.recipe.pk).exists())
