class RecipeModelTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.user = make_user()

    def test_str_and_absolute_url(self):
        recipe = make_recipe(self.user, name='Gumbo')
        self.assertEqual(str(recipe), 'Gumbo')
        self.assertEqual(
            recipe.get_absolute_url(),
            reverse('cookbook:recipe_detail', kwargs={'pk': recipe.pk}),
        )

    def test_total_minutes_none_when_both_unset(self):
        recipe = make_recipe(self.user)
        self.assertIsNone(recipe.total_minutes)

    def test_total_minutes_sums_and_treats_missing_as_zero(self):
        self.assertEqual(make_recipe(self.user, prep_minutes=10, cook_minutes=20).total_minutes, 30)
        self.assertEqual(make_recipe(self.user, prep_minutes=15).total_minutes, 15)
        self.assertEqual(make_recipe(self.user, cook_minutes=5).total_minutes, 5)

    def test_has_nutrition(self):
        self.assertFalse(make_recipe(self.user).has_nutrition)
        self.assertTrue(make_recipe(self.user, calories=100).has_nutrition)
        self.assertTrue(make_recipe(self.user, protein_g=3).has_nutrition)


class IngredientStepPhotoModelTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.recipe = make_recipe(make_user())

    def test_ingredient_display_joins_present_parts(self):
        full = Ingredient(recipe=self.recipe, quantity='2', unit='cups', text='flour')
        self.assertEqual(full.display, '2 cups flour')
        self.assertEqual(str(full), '2 cups flour')

    def test_ingredient_display_skips_blank_parts(self):
        bare = Ingredient(recipe=self.recipe, text='salt')
        self.assertEqual(bare.display, 'salt')

    def test_step_str(self):
        step = Step(recipe=self.recipe, instruction='Boil the water thoroughly', order=1)
        self.assertIn('Step 1', str(step))
        self.assertIn('Boil', str(step))

    def test_photo_str_uses_caption_then_fallback(self):
        self.assertEqual(str(RecipePhoto(recipe=self.recipe, caption='Plated')), 'Plated')
        self.assertIn('Photo', str(RecipePhoto(recipe=self.recipe)))


class RecipeListViewTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.user = make_user()
        cls.dinner = Category.objects.create(name='Dinner')
        cls.dessert = Category.objects.create(name='Dessert')
        cls.gumbo = make_recipe(cls.user, name='Chicken Gumbo', description='cajun stew')
        cls.gumbo.categories.add(cls.dinner)
        Ingredient.objects.create(recipe=cls.gumbo, text='okra')
        cls.cake = make_recipe(cls.user, name='Carrot Cake', description='sweet')
        cls.cake.categories.add(cls.dessert)

    def test_list_shows_all_recipes(self):
        resp = self.client.get(reverse('cookbook:recipe_list'))
        self.assertEqual(resp.status_code, 200)
        self.assertContains(resp, 'Chicken Gumbo')
        self.assertContains(resp, 'Carrot Cake')

    def test_search_matches_name(self):
        resp = self.client.get(reverse('cookbook:recipe_list'), {'q': 'gumbo'})
        self.assertContains(resp, 'Chicken Gumbo')
        self.assertNotContains(resp, 'Carrot Cake')

    def test_search_matches_ingredient_text(self):
        resp = self.client.get(reverse('cookbook:recipe_list'), {'q': 'okra'})
        self.assertContains(resp, 'Chicken Gumbo')
        self.assertNotContains(resp, 'Carrot Cake')
        self.assertEqual(resp.context['query'], 'okra')

    def test_category_filter(self):
        resp = self.client.get(
            reverse('cookbook:category_detail', kwargs={'slug': 'dessert'})
        )
        self.assertEqual(resp.status_code, 200)
        self.assertContains(resp, 'Carrot Cake')
        self.assertNotContains(resp, 'Chicken Gumbo')
        self.assertEqual(resp.context['category'], self.dessert)

    def test_unknown_category_404s(self):
        resp = self.client.get(
            reverse('cookbook:category_detail', kwargs={'slug': 'nope'})
        )
        self.assertEqual(resp.status_code, 404)


